// Command codegen generates the fireblocks-go models, services and API
// reference documentation from the Fireblocks OpenAPI specification.
//
// Usage (from the repository root):
//
//	go generate ./...
package main

import (
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const header = "// Code generated by internal/codegen from api/openapi.yaml. DO NOT EDIT.\n\n"

// reserved are exported identifiers declared by hand-written files of package fireblocks.
var reserved = []string{
	"Client", "NewClient", "NewClientWithSigner", "NewClientFromEnv", "ClientOption", "RequestOption",
	"APIError", "AsAPIError", "IsNotFound", "IsUnauthorized", "IsRateLimited", "File", "Ptr", "Deref", "APISpecVersion", "Version",
	"ProductionBaseURL", "SandboxBaseURL", "EUBaseURL", "EU2BaseURL",
	"WithBaseURL", "WithHTTPClient", "WithUserAgent", "WithMaxRetries", "WithRetryBackoff", "WithLogger",
	"WithIdempotencyKey", "WithHeader", "WithQueryParam", "WithRetries", "OnResponse",
	"VerifyWebhookSignature", "ParseRSAPublicKeyPEM", "ParseRSAPrivateKeyPEM",
	"ErrMissingParameter", "ErrInvalidWebhookSignature",
}

func main() {
	specPath := flag.String("spec", "api/openapi.yaml", "path to the OpenAPI specification")
	outDir := flag.String("out", ".", "output directory for Go files")
	docsDir := flag.String("docs", "docs/api", "output directory for generated Markdown, relative to -out")
	includeInternal := flag.Bool("include-internal", false, "also generate operations marked x-internal")
	flag.Parse()

	spec, err := loadSpec(*specPath)
	if err != nil {
		log.Fatalf("load spec: %v", err)
	}
	g := newGen(spec)
	for _, r := range reserved {
		g.idents[r] = true
	}
	services := g.buildServices(*includeInternal)
	for _, name := range spec.Components.Schemas.Names {
		g.comp[name] = g.idents.unique(pascalType(name))
	}
	g.genComponents()
	for _, svc := range services {
		g.genService(svc)
	}

	files := map[string]*strings.Builder{}
	get := func(name string) *strings.Builder {
		if b, ok := files[name]; ok {
			return b
		}
		b := &strings.Builder{}
		files[name] = b
		return b
	}

	for _, svc := range services {
		b := get(svc.File)
		b.WriteString(header + "package fireblocks\n\nimport (\n\t\"context\"\n\t\"net/http\"\n)\n\n")
		fmt.Fprintf(b, "// %s groups the %q endpoints of the Fireblocks API.\n//\n// Use it through Client.%s.\n", svc.Type, svc.Tag, svc.GoName)
		fmt.Fprintf(b, "type %s struct{ core *core }\n", svc.Type)
		b.WriteString(svc.Code.String())
	}
	for _, d := range g.decls {
		b, ok := files[d.File]
		if !ok {
			b = get(d.File)
			b.WriteString(header + "package fireblocks\n")
		}
		b.WriteString("\n" + d.Code)
	}

	cb := get("client.gen.go")
	cb.WriteString(header + "package fireblocks\n\n")
	cb.WriteString("// Client is a Fireblocks API client. Each field groups the endpoints of one\n// API area; create a Client with NewClient, NewClientWithSigner or NewClientFromEnv.\n//\n// A Client is safe for concurrent use.\ntype Client struct {\n\tcore *core\n\n")
	for _, svc := range services {
		fmt.Fprintf(cb, "\t// %s provides the %q endpoints.\n\t%s *%s\n", svc.GoName, svc.Tag, svc.GoName, svc.Type)
	}
	cb.WriteString("}\n\nfunc newClient(c *core) *Client {\n\treturn &Client{\n\t\tcore: c,\n")
	for _, svc := range services {
		fmt.Fprintf(cb, "\t\t%s: &%s{core: c},\n", svc.GoName, svc.Type)
	}
	cb.WriteString("\t}\n}\n")
	fmt.Fprintf(cb, "\n// APISpecVersion is the version of the Fireblocks OpenAPI specification this package was generated from.\nconst APISpecVersion = %q\n", spec.Info.Version)

	// Remove stale generated files before writing.
	old, _ := filepath.Glob(filepath.Join(*outDir, "*.gen.go"))
	for _, f := range old {
		if err := os.Remove(f); err != nil {
			log.Fatal(err)
		}
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		src := []byte(files[n].String())
		formatted, err := format.Source(src)
		if err != nil {
			_ = os.WriteFile(filepath.Join(*outDir, n+".broken"), src, 0o644)
			log.Fatalf("format %s: %v", n, err)
		}
		if err := os.WriteFile(filepath.Join(*outDir, n), formatted, 0o644); err != nil {
			log.Fatal(err)
		}
	}

	if err := writeDocs(filepath.Join(*outDir, *docsDir), spec, services); err != nil {
		log.Fatalf("docs: %v", err)
	}
	ops := 0
	for _, s := range services {
		ops += len(s.Ops)
	}
	log.Printf("generated %d services, %d operations, %d declarations into %d files", len(services), ops, len(g.decls), len(files))
}

// pascalType names a component schema, keeping its original spelling when it
// is already a valid exported identifier so types stay recognisable.
func pascalType(name string) string {
	p := pascal(name)
	if p == "" {
		return "Schema"
	}
	return p
}
