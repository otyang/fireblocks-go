package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const pkgDoc = "https://pkg.go.dev/github.com/otyang/fireblocks-go"

var typeIdentRE = regexp.MustCompile(`[A-Z][A-Za-z0-9]*`)

// linkType renders a Go type expression with links to pkg.go.dev for named types.
func linkType(expr string) string {
	if expr == "" {
		return ""
	}
	m := typeIdentRE.FindString(expr)
	if m == "" {
		return "`" + expr + "`"
	}
	return fmt.Sprintf("[`%s`](%s#%s)", expr, pkgDoc, m)
}

func mdCell(s string) string {
	s = cleanText(s)
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	if r := []rune(s); len(r) > 300 {
		s = string(r[:297]) + "..."
	}
	return s
}

func anchor(s string) string { return strings.ToLower(s) }

// demoteHeadings keeps spec-provided Markdown headings below the per-method heading level.
func demoteHeadings(s string) string {
	lines := strings.Split(s, "\n")
	inFence := false
	for i, l := range lines {
		if t := strings.TrimSpace(l); strings.HasPrefix(t, "```") || strings.HasPrefix(t, "~~~") {
			inFence = !inFence
			continue
		}
		if !inFence && strings.HasPrefix(l, "#") {
			lines[i] = "###" + l
		}
	}
	return strings.Join(lines, "\n")
}

func writeDocs(dir string, spec *Spec, services []*Service) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	old, _ := filepath.Glob(filepath.Join(dir, "*.md"))
	for _, f := range old {
		_ = os.Remove(f)
	}

	var idx strings.Builder
	idx.WriteString("<!-- Code generated by internal/codegen. DO NOT EDIT. -->\n\n")
	idx.WriteString("# API reference\n\n")
	fmt.Fprintf(&idx, "Generated from the Fireblocks OpenAPI specification **v%s**. Every service is a field on `*fireblocks.Client`.\n\n", spec.Info.Version)
	idx.WriteString("For model types (request and response structs, enums, unions) see the [Go package documentation](" + pkgDoc + ").\n\n")
	idx.WriteString("| Service | Client field | Operations |\n|---|---|---|\n")

	for _, svc := range services {
		file := snake(svc.GoName) + ".md"
		fmt.Fprintf(&idx, "| [%s](%s) | `client.%s` | %d |\n", svc.Tag, file, svc.GoName, len(svc.Ops))

		var b strings.Builder
		b.WriteString("<!-- Code generated by internal/codegen. DO NOT EDIT. -->\n\n")
		fmt.Fprintf(&b, "# %s\n\n", svc.Tag)
		fmt.Fprintf(&b, "Accessed through `client.%s` ([`%s`](%s#%s)). [Back to index](README.md).\n\n", svc.GoName, svc.Type, pkgDoc, svc.Type)
		b.WriteString("| Method | Endpoint | Summary |\n|---|---|---|\n")
		for _, op := range svc.Ops {
			dep := ""
			if op.Deprecated {
				dep = " *(deprecated)*"
			}
			fmt.Fprintf(&b, "| [%s](#%s)%s | `%s %s` | %s |\n", op.GoName, anchor(op.GoName), dep, op.Method, op.Path, mdCell(op.Summary))
		}
		for _, op := range svc.Ops {
			fmt.Fprintf(&b, "\n## %s\n\n", op.GoName)
			fmt.Fprintf(&b, "```go\n%s\n```\n\n", op.Signature)
			meta := fmt.Sprintf("`%s %s`", op.Method, op.Path)
			if op.RateLimit != "" {
				meta += fmt.Sprintf(" · rate-limit category: `%s`", op.RateLimit)
			}
			if op.Deprecated {
				meta += " · **deprecated**"
			}
			b.WriteString(meta + "\n\n")
			if s := cleanText(op.Summary); s != "" {
				fmt.Fprintf(&b, "**%s**\n\n", s)
			}
			if d := cleanText(op.Description); d != "" && d != cleanText(op.Summary) {
				b.WriteString(demoteHeadings(d) + "\n\n")
			}
			if len(op.Params) > 0 {
				b.WriteString("**Parameters**\n\n| Name | In | Type | Required | Description |\n|---|---|---|---|---|\n")
				for _, p := range op.Params {
					req := ""
					if p.Required {
						req = "yes"
					}
					fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", p.Name, p.In, linkType(p.Type), req, mdCell(p.Description))
				}
				b.WriteString("\n")
			}
			if op.BodyType != "" {
				fmt.Fprintf(&b, "**Request body:** %s\n\n", linkType(op.BodyType))
			}
			if op.ResultType != "" {
				fmt.Fprintf(&b, "**Returns:** %s\n", linkType(op.ResultType))
			} else {
				b.WriteString("**Returns:** only an `error`.\n")
			}
		}
		if err := os.WriteFile(filepath.Join(dir, file), []byte(b.String()), 0o644); err != nil {
			return err
		}
	}
	return os.WriteFile(filepath.Join(dir, "README.md"), []byte(idx.String()), 0o644)
}
